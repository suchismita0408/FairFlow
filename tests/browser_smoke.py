"""Agile v2 browser smoke. Run against the local DEMO server. Creates labeled demo data."""
import httpx
from playwright.sync_api import sync_playwright, expect
assert httpx.get('http://127.0.0.1:8000/api/health').json()['payment_mode']=='demo'
with sync_playwright() as pw:
    browser=pw.chromium.launch()
    page=browser.new_page(viewport={'width':1440,'height':1000})
    errors=[]
    page.on('pageerror',lambda error:errors.append(str(error)))
    page.goto('http://127.0.0.1:8000')
    page.locator('#new-project').click()
    page.locator('#sample').click()
    page.locator('#extract').click()
    expect(page.locator('.plan-row')).to_have_count(3)
    page.locator('#title').fill('Agile coffee studio (demo)')
    page.locator('#create-form button[type=submit]').click()
    expect(page.locator('#create-modal')).not_to_be_visible()
    for role in ['client','freelancer']:
        page.locator(f'[data-agile=accept][data-role={role}]').click()
    expect(page.locator('#vault-consent')).to_be_visible()
    page.locator('#vault-consent').check()
    page.locator('[data-agile=vault-setup]').click()
    page.locator('[data-agile=vault-confirm]').click()
    page.locator('[data-agile=fund]').click()
    expect(page.locator('.funding-indicator.green')).to_have_count(1)
    first=page.locator('.milestone-card').first
    mid=first.get_attribute('id').removeprefix('milestone-')
    first.get_by_text('Delayed sprint · record partial progress',exact=True).click()
    page.locator('#evidence-'+mid).fill('https://example.com/demo-progress')
    page.locator('#completed-'+mid).fill('Layout, branding and responsive components are delivered.')
    page.locator('#remaining-'+mid).fill('Complete the accessibility review and handoff documentation.')
    page.locator('[data-agile=progress]').click()
    page.locator('[data-agile=progress-accept]').click()
    page.locator('.demo-controls summary').click()
    page.locator('[data-agile=billing-fail]').click()
    page.locator('.demo-controls summary').click()
    page.locator('[data-agile=advance][data-days="28"]').click()
    expect(page.locator('.badge.billing_failed')).to_be_visible()
    expect(page.locator('.badge.rolled_over')).to_be_visible()
    page.evaluate('window.scrollTo(0,0)')
    page.screenshot(path='docs/agile-red-light.png',full_page=True)
    page.locator('.demo-controls summary').click()
    page.locator('[data-agile=billing-fix]').click()
    page.locator('[data-agile=fund]').click()
    expect(page.locator('.funding-indicator.green')).to_have_count(1)
    page.locator('#pause-reason').fill('Medical emergency: pause work until recovery.')
    page.locator('[data-agile=pause]').click()
    expect(page.locator('[data-agile=resume]')).to_be_visible()
    expect(page.locator('.funding-indicator.green')).to_have_count(0)
    page.locator('[data-agile=resume]').click()
    expect(page.locator('.funding-indicator.green')).to_have_count(1)
    second=page.locator('.milestone-card').nth(1)
    mid2=second.get_attribute('id').removeprefix('milestone-')
    second.get_by_text('Revision firewall & disputes',exact=True).click()
    page.locator('#request-'+mid2).fill('Add a database backend and customer login')
    page.locator('[data-agile=change]').click()
    expect(page.locator('.badge.proposed')).to_be_visible()
    for role in ['client','freelancer']:
        page.locator(f'[data-agile=addition][data-role={role}]').click()
    expect(page.locator('.badge.proposed')).to_have_count(0)
    second=page.locator('.milestone-card').nth(1)
    second.get_by_text('Submit a completed milestone',exact=True).click()
    page.locator('#delivery-'+mid2).fill('https://example.com/demo-delivery')
    page.locator('#notes-'+mid2).fill('Demo delivery with approved carry-over included.')
    page.locator('[data-agile=deliver]').click()
    expect(page.locator('.agile-countdown')).to_be_visible()
    page.evaluate('window.scrollTo(0,0)')
    page.screenshot(path='docs/agile-desktop.png',full_page=True)
    page.locator('.demo-controls summary').click()
    page.locator('[data-agile=advance][data-days="5"]').click()
    expect(page.locator('.milestone-card').nth(1).locator('.badge.completed')).to_be_visible()
    expect(page.locator('.milestone-card').nth(2).locator('.badge.active')).to_be_visible()
    page.set_viewport_size({'width':390,'height':844})
    page.evaluate('window.scrollTo(0,0)')
    page.screenshot(path='docs/agile-mobile.png',full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'Mobile horizontal overflow'
    assert not errors,errors
    browser.close()
    print('Agile browser smoke PASSED: plan/consent/vault, funding, 80% rollover, red light, billing recovery, emergency void/resume, paid addition consent, five-day capture, next funding, mobile layout; no JS errors.')
